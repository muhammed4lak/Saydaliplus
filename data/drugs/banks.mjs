/* ==========================================================================
   THE BANKS — the shared vocabulary every drug entry draws on.

   A drug entry names things by key rather than re-typing them, for three
   reasons:

   1. THE SAME QUESTION READS THE SAME WAY EVERYWHERE. The Helper merges the
      questions of every drug in a basket into one list, matched on the text.
      Three drugs that all need "are you pregnant?" should produce one
      question, and they only can if all three say it in the same words.
   2. A CORRECTION IS MADE ONCE. Rewording a contraindication fixes it on every
      drug that carries it.
   3. CLASS INTERACTIONS ARE WRITTEN ONCE. An NSAID with an anticoagulant is a
      bleeding risk whichever NSAID and whichever anticoagulant; writing it on
      forty pairs by hand is how thirty-nine of them end up missing.

   Anything specific to one drug is still written on that drug, in full.

   Everything here is placeholder clinical content until the clinical curator
   (W19) has reviewed it, like the rest of the reference.
   ========================================================================== */

